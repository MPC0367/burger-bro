export function lang() {
  const l = (document.body && document.body.dataset.lang) || document.documentElement.lang || "en";
  return l === "th" ? "th" : "en";
}
export function t(key, vars = {}) {
  const l = lang();
  let s = (STR[l] && STR[l][key]) ?? STR.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll("{" + k + "}", String(v));
  return s;
}
export function errText(code) {
  const k = "err_" + code;
  return STR.en[k] ? t(k) : t("err_generic");
}
